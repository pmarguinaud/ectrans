SUBROUTINE TRANSLATE(N, A, B, C, P)
! acc2omp.pl translation: one case per row of the table
INTEGER :: N, J, K
REAL :: A(N,N), B(N,N), C(N)
REAL, OPTIONAL :: P(N)
!$ACC DATA PRESENT(A) COPYIN(B) COPYOUT(C) IF(N > 0) ASYNC(1) ! trailing comment
!$ACC DATA COPY(A) CREATE(B)
!$ACC END DATA
!$ACC PARALLEL LOOP COLLAPSE(2) PRIVATE(K) DEFAULT(NONE) &
!$ACC& FIRSTPRIVATE(N) ASYNC(1) &
!$ACC& PRESENT(A, B)
DO J=1,N
  DO K=1,N
    A(K,J) = B(K,J)
  ENDDO
ENDDO
!$ACC PARALLEL LOOP TILE(32,16) DEFAULT(NONE) PRESENT(A,B,C(1:N),&
!$ACC & B)
DO J=1,N
  !$ACC LOOP SEQ
  DO K=1,N
    A(K,J) = A(K,J) + B(K,J)
  ENDDO
ENDDO
!$ACC END PARALLEL LOOP
!$ACC UPDATE HOST(A) DEVICE(B) IF(N > 1) ASYNC(1)
!$ACC WAIT(1)
!$ACC WAIT
!$ACC HOST_DATA USE_DEVICE(A, B)
CALL SOMETHING(A, B)
!$ACC END HOST_DATA
!$ACC END DATA
!$ACC ENTER DATA COPYIN(A) CREATE(B) IF(N > 0) ASYNC(1)
!$ACC EXIT DATA DELETE(B) COPYOUT(A) IF(N > 0)
! optional argument: P is dropped from PRESENT on the loop, also inside a hand-written pair
#ifdef ACCGPU
!$ACC DATA PRESENT(A,P) IF(PRESENT(P))
#endif
#ifdef OMPGPU
!$OMP TARGET DATA MAP(PRESENT,ALLOC:A,P) IF(PRESENT(P))
#endif
IF (PRESENT(P)) THEN
!$ACC PARALLEL LOOP PRESENT(A,P)
DO J=1,N
  A(J,1) = P(J)
ENDDO
ENDIF
#ifdef ACCGPU
!$ACC END DATA
#endif
#ifdef OMPGPU
!$OMP END TARGET DATA
#endif
!$ACC PARALLEL LOOP PRESENT(P)
DO J=1,N
  P(J) = 0.
ENDDO
END SUBROUTINE
