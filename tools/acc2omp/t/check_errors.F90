SUBROUTINE CHECK_ERRORS(N, A)
INTEGER :: N, J
REAL :: A(N)
!$ACC KERNELS
A = 0.
!$ACC END KERNELS
!$ACC PARALLEL LOOP GANG VECTOR DEFAULT(PRESENT)
DO J=1,N
  A(J) = 1.
ENDDO
!$ACC PARALLEL LOOP TILE(32) COLLAPSE(1)
DO J=1,N
  A(J) = 1.
ENDDO
!$ACC LOOP
!$ACC UPDATE SELF(A)
!$ACC ROUTINE SEQ
!$ACC PARALLEL LOOP &
#ifdef SOMETHING
!$ACC& ASYNC(1)
#endif
DO J=1,N
  A(J) = 1.
ENDDO
END SUBROUTINE
