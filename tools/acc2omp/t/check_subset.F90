SUBROUTINE CHECK_SUBSET(N, A, B)
! In the subset: no error expected
INTEGER :: N, J, K
REAL :: A(N,N), B(N,N)
!$ACC DATA PRESENT(A) COPYIN(B) IF(N > 0) ASYNC(1) ! trailing comment
!$ACC PARALLEL LOOP COLLAPSE(2) PRIVATE(K) DEFAULT(NONE) &
!$ACC& FIRSTPRIVATE(N) ASYNC(1)
DO J=1,N
  DO K=1,N
    A(K,J) = B(K,J)
  ENDDO
ENDDO
!$ACC PARALLEL LOOP TILE(32,16) DEFAULT(NONE) PRESENT(A,B)
DO J=1,N
  !$ACC LOOP SEQ
  DO K=1,N
    A(K,J) = A(K,J) + B(K,J)
  ENDDO
ENDDO
!$ACC END PARALLEL LOOP
!$ACC UPDATE HOST(A) ASYNC(1)
!$ACC WAIT(1)
!$ACC WAIT
!$ACC HOST_DATA USE_DEVICE(A)
!$ACC END HOST_DATA
!$ACC END DATA
!$ACC ENTER DATA COPYIN(A) CREATE(B)
!$ACC EXIT DATA DELETE(B) COPYOUT(A)
#ifdef ACCGPU
!$ACC KERNELS
A = 0.
!$ACC END KERNELS
#endif
END SUBROUTINE
